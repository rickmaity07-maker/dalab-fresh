export const DICTS: Record<Lang, Dict> = { de, en, so };

const LOCALE: Record<Lang, string> = { de: "de-DE", en: "en-GB", so: "so-SO" };

// Browsers ship little or no Somali date data (Chrome falls back to English), so Somali dates are built by hand.
const SO_DAYS = ["Axad", "Isniin", "Talaado", "Arbaco", "Khamiis", "Jimce", "Sabti"];
const SO_MONTHS = ["Janaayo", "Febraayo", "Maarso", "Abriil", "May", "Juun", "Luulyo", "Ogosto", "Sebtembar", "Oktoobar", "Nofembar", "Desembar"];

/** Formats a Berlin calendar date (held as UTC midnight) in the given language. */
export function formatDay(utc: Date, lang: Lang, opts: Intl.DateTimeFormatOptions) {
  if (lang === "so") {
    const short = (s: string) => (s.length > 4 ? s.slice(0, 3) : s);
    const day = SO_DAYS[utc.getUTCDay()];
    const month = SO_MONTHS[utc.getUTCMonth()];
    const parts = [
      opts.weekday ? (opts.weekday === "long" ? day : short(day)) : "",
      opts.day ? `${utc.getUTCDate()}${opts.month ? ` ${opts.month === "long" ? month : short(month)}` : ""}` : "",
    ].filter(Boolean);
    return parts.join(", ");
  }
  return utc.toLocaleDateString(LOCALE[lang], { ...opts, timeZone: "UTC" });
}

/** "Heute, 14:00-16:00" / "Friday, 10:00-12:00". */
export function describeSlot(slotId: string, now: Date, lang: Lang): string {
  const t = DICTS[lang].services;
  const s = parseSlot(slotId, now);
  if (s.express) return t.expressLabel;
  const day = s.dayIndex === 0 ? t.today : s.dayIndex === 1 ? t.tomorrow : formatDay(s.utc, lang, { weekday: "long", day: "numeric", month: "long" });
  return `${day}, ${s.range}`;
}
